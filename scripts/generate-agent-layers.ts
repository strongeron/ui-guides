#!/usr/bin/env npx tsx
/**
 * Generate the sliceable payloads an agent in another repo fetches on demand.
 *
 * The problem this solves is token cost. `llms-full.txt` is the whole corpus at
 * ~166k tokens — more than most agents can spend, and the only slice available
 * before this was `curl | awk` on a category heading. The ladder below lets an
 * agent pay for what it reads:
 *
 *   principles/index.md        pick ids            (all 404, compact)
 *   principles/must.md         the MUST gate       (191 rules)
 *   categories/<id>.md         one category        (rules + prose, no code)
 *   principles/<id>.md         one rule + BOTH examples' source
 *
 * The per-rule payload is the point: 809 example components, 3.3 MB, were
 * unreachable from any endpoint, so an agent got the assertion without the
 * demonstration. Category files deliberately omit example source — 89 rules of
 * code would defeat the reason to fetch a category instead of everything.
 *
 * Output is gitignored and regenerated by `prebuild`; Vite copies public/ into
 * dist/, so the files exist on the deploy without 800+ generated blobs in git.
 */

import { mkdirSync, rmSync, writeFileSync } from 'fs';
import { join } from 'path';
import {
  PUBLIC_DIR,
  SITE,
  loadExampleSources,
  published,
  sourceInfo,
} from './lib/corpus';
import { agentRules } from '../src/data/agentRules';
import { categories } from '../src/data/principles';
import type { Principle } from '../src/types/principle';

const PRINCIPLES_DIR = join(PUBLIC_DIR, 'principles');
const CATEGORIES_DIR = join(PUBLIC_DIR, 'categories');

const examples = loadExampleSources();

/** ~4 chars/token is close enough to size a payload and cheaper than a tokenizer. */
const tokens = (s: string) => Math.round(s.length / 4);

/**
 * Trigger symbols — what makes the index navigable rather than a list to guess from.
 *
 * A title tells an agent almost nothing about whether a rule applies to the file in
 * front of it ("Enter Submits" does not say `onSubmit`), and the tag vocabulary is too
 * coarse to help: 7 tags over 404 rules, 39% of them untagged. So each rule is
 * annotated with the concrete symbols its own examples use. An agent can then match
 * the identifiers already in its diff instead of reasoning about titles.
 *
 * Symbols are mined from the good and bad example source plus the rule text, then
 * filtered by document frequency: anything in more than 16% of rules is React or UI
 * boilerplate (`onClick`, `useState`, `<button>`) and discriminates nothing, and
 * anything unique to one rule is usually incidental. What survives reaches ~60% of the
 * corpus — the mechanical rules. The rest are judgment calls about design and prose,
 * where the category is the right axis and no symbol would help.
 */
const SYMBOL_PATTERNS: RegExp[] = [
  /\bon[A-Z][a-zA-Z]+/g, // JSX handlers
  /\baria-[a-z-]+/g,
  /<(form|dialog|button|input|label|select|textarea|table|nav|img|video|a)\b/g,
  /\b(transition|transform|animation|overscroll-behavior|will-change|opacity|scroll-behavior|touch-action|user-select|contain)\b/g,
  /\b(tabIndex|autoComplete|autoFocus|inputMode|enterKeyHint|role|type|alt|lang|dir|loading|decoding|hidden|disabled|required|placeholder)=/g,
  /\b(useEffect|useState|useRef|requestAnimationFrame|setTimeout|IntersectionObserver|ResizeObserver|matchMedia|prefers-reduced-motion|preventDefault)\b/g,
  // Pseudo-classes and sizing idioms carry several rules that name no JS API at all —
  // focus styling, tap-target size, and the iOS zoom threshold among them.
  /:focus-visible|:focus-within|focus\(\)|font-size|min-h-|min-w-/g,
];

/**
 * Above this share of the corpus a symbol is boilerplate and carries no signal.
 *
 * 0.16 rather than 0.15 because `<label>` sits right on the old line (62 of 411 rules,
 * 15.1%) and is nothing like the boilerplate the ceiling exists to drop — it is the
 * entry point to the whole label/`htmlFor` family. At 0.15 a single new example that
 * happens to render a label deletes `label` from the 32 rule lines that carry it, with
 * no build failure to notice. Measured: raising the ceiling to 0.16 admits exactly one
 * additional symbol corpus-wide (`label`) and drops none.
 */
const MAX_DOC_FREQUENCY = 0.16;

/** Enough to match on without turning every index line into a wall of tokens. */
const MAX_TRIGGERS_PER_RULE = 4;

function buildTriggers(): Map<string, string[]> {
  const candidates = new Map<string, Set<string>>();

  for (const p of published) {
    const haystack = [
      examples.get(p.goodExampleKey) ?? '',
      examples.get(p.badExampleKey) ?? '',
      agentRules[p.id]?.rule ?? '',
    ].join('\n');

    const found = new Set<string>();
    for (const pattern of SYMBOL_PATTERNS) {
      for (const [match] of haystack.matchAll(pattern)) {
        found.add(match.replace(/[<=]/g, ''));
      }
    }
    candidates.set(p.id, found);
  }

  const frequency = new Map<string, number>();
  for (const found of candidates.values()) {
    for (const symbol of found) frequency.set(symbol, (frequency.get(symbol) ?? 0) + 1);
  }
  const ceiling = published.length * MAX_DOC_FREQUENCY;

  const triggers = new Map<string, string[]>();
  for (const [id, found] of candidates) {
    triggers.set(
      id,
      [...found]
        .filter((s) => {
          const n = frequency.get(s)!;
          return n >= 2 && n <= ceiling;
        })
        // Rarest first: the most distinctive symbol is the most useful to match on.
        .sort((a, b) => frequency.get(a)! - frequency.get(b)! || a.localeCompare(b))
        .slice(0, MAX_TRIGGERS_PER_RULE),
    );
  }
  return triggers;
}

const triggers = buildTriggers();

/**
 * Surfaces — the "what am I building" axis, modelled on the WAI-ARIA APG, which
 * organises by the thing being built rather than by concern or severity. An agent
 * works on a dialog or a form, not on "the animations category".
 *
 * APG can make that a clean partition because each of its pages *is* a component.
 * This corpus cannot: measured across all 404 rules, a rule belongs to 2.1 surfaces on
 * average, because "visible focus rings" genuinely applies to buttons and forms and
 * dialogs and links alike. So surfaces are labels, not folders — every rule keeps
 * exactly one canonical file, and the lookup is multi-label. Re-partitioning the
 * filesystem this way would force false single-parents or duplicate rules on disk.
 *
 * 43 rules match no surface. They stay reachable by category and by trigger symbol,
 * and the index says so rather than inventing a bucket for them.
 */
const SURFACE_PATTERNS: [string, RegExp][] = [
  ['focus-keyboard', /\b(focus|keyboard|tab order|tabindex|hit target|touch target|shortcut|arrow key|escape|enter key|aria-|role=|semantic)\b/i],
  ['form-input', /\b(form|input|field|textarea|select|checkbox|radio|label|validation|submit|autocomplete|placeholder|password)\b/i],
  ['button-action', /\b(button|cta|click|tap|press|action|destructive|confirm|clickable|interactive)\b/i],
  ['dialog-overlay', /\b(modal|dialog|drawer|sheet|overlay|popover|backdrop|tooltip|hint)\b/i],
  ['menu-select', /\b(menu|dropdown|combobox|listbox|command palette)\b/i],
  ['nav-link', /\b(link|anchor|nav|navigation|breadcrumb|tab|router|route|href)\b/i],
  ['table-list', /\b(table|grid|row|column|list|virtual|infinite scroll|pagination)\b/i],
  ['media', /\b(image|img|video|canvas|svg|icon|picture|media|poster)\b/i],
  ['feedback-status', /\b(toast|alert|loading|skeleton|spinner|empty state|error|announce|live region|progress|optimistic)\b/i],
  ['scroll-overflow', /\b(scroll|overflow|overscroll|sticky|viewport)\b/i],
  ['text-typography', /\b(typography|font|text|heading|line-height|letter|truncat|wrap|copy|label)\b/i],
  ['color-theme', /\b(color|contrast|theme|dark mode|palette|hue|opacity|shadow)\b/i],
  ['motion', /\b(animation|animate|transition|motion|easing|duration|spring)\b/i],
  ['layout-spacing', /\b(layout|spacing|align|margin|padding|responsive|breakpoint|container|z-index|zoom)\b/i],
  ['perf-loading', /\b(performance|bundle|render|lazy|defer|prefetch|cache|memo|paint|layout shift|hydrat)\b/i],
];

const surfaceOf = (p: Principle): string[] => {
  const haystack = [
    p.title,
    p.description,
    agentRules[p.id]?.rule ?? '',
    (p.tags ?? []).join(' '),
  ].join(' ');
  return SURFACE_PATTERNS.filter(([, re]) => re.test(haystack)).map(([name]) => name);
};

const surfaces = new Map(published.map((p) => [p.id, surfaceOf(p)]));

const permalink = (id: string) => `${SITE}/principles/${id}.md`;

const sourceLine = (p: Principle) => {
  const info = sourceInfo(p.source);
  if (!info) return null;
  return `**Source:** ${info.url ? `[${info.name}](${info.url})` : info.name}`;
};

/**
 * Rule + prose, no example code. Shared by the category files and by the head of
 * each per-rule payload — hence `self`, which decides where the cross-link points:
 * a category file sends the reader to the payload, and the payload, which would
 * otherwise cite itself, sends them to the page a human reads.
 */
function ruleSection(p: Principle, heading = '##', self = false): string {
  const rule = agentRules[p.id];
  const out = [`${heading} ${p.title}`, ''];

  const meta = [`**ID:** \`${p.id}\``, `**Category:** ${p.category}`];
  if (rule) meta.unshift(`**${rule.priority}**`);
  out.push(meta.join(' · '));

  const src = sourceLine(p);
  if (src) out.push(src);
  out.push(
    self
      ? `**Interactive version:** ${SITE}/principles/${p.id}`
      : `**Full rule + examples:** ${permalink(p.id)}`,
    '',
  );

  if (rule) out.push(`> ${rule.priority}: ${rule.rule}`, '');
  out.push(p.description);
  if (p.additionalExplanation) out.push('', p.additionalExplanation);

  return out.join('\n');
}

/** One rule, with both example components inline — the payload agents apply from. */
function rulePayload(p: Principle): string {
  const rule = agentRules[p.id];
  const out = [ruleSection(p, '#', true)];

  if (rule?.codeExample) {
    out.push('', '## Rule snippet', '', '```tsx', rule.codeExample.trim(), '```');
  }

  for (const [label, key] of [
    ['Bad — do not do this', p.badExampleKey],
    ['Good — do this', p.goodExampleKey],
  ] as const) {
    const source = examples.get(key);
    if (!source) continue;
    out.push('', `## ${label}`, '', `\`${key}\``, '', '```tsx', source.trim(), '```');
  }

  if (p.sourceLinks?.length) {
    out.push('', '## References', '');
    out.push(...p.sourceLinks.map((l) => `- [${l.text}](${l.url})`));
  }

  return out.join('\n') + '\n';
}

function ruleJson(p: Principle) {
  const rule = agentRules[p.id];
  const info = sourceInfo(p.source);
  return {
    id: p.id,
    title: p.title,
    category: p.category,
    tags: p.tags ?? [],
    surfaces: surfaces.get(p.id) ?? [],
    triggers: triggers.get(p.id) ?? [],
    priority: rule?.priority ?? null,
    rule: rule?.rule ?? null,
    ruleSnippet: rule?.codeExample ?? null,
    description: p.description,
    explanation: p.additionalExplanation ?? null,
    source: info ? { id: p.source, name: info.name, url: info.url ?? null } : null,
    references: p.sourceLinks ?? [],
    examples: {
      bad: { key: p.badExampleKey, source: examples.get(p.badExampleKey) ?? null },
      good: { key: p.goodExampleKey, source: examples.get(p.goodExampleKey) ?? null },
    },
    urls: { markdown: permalink(p.id), json: `${SITE}/principles/${p.id}.json` },
  };
}

/**
 * The navigation entry point. One index, one axis to search: every rule line ends in
 * match tokens — the surface it belongs to and the symbols its examples use — so
 * finding a rule is a text search, not a judgement about which category a concern
 * lives in. An agent building a modal should not have to know that focus, motion and
 * ARIA rules are filed in three different categories.
 */
function indexMd(): string {
  const counts = new Map<string, number>();
  for (const list of surfaces.values()) {
    for (const s of list) counts.set(s, (counts.get(s) ?? 0) + 1);
  }
  const vocabulary = [...counts]
    .sort((a, b) => b[1] - a[1])
    .map(([name, n]) => `${name} (${n})`);
  const unclassified = published.filter((p) => !surfaces.get(p.id)!.length).length;

  const out = [
    '# Rule index',
    '',
    `${published.length} rules. Every line below ends with match tokens after a \`·\`.`,
    'Search this file for a token; fetch only what matched. Nothing here is the rule',
    'itself.',
    '',
    '## 1. Search by what you are building',
    '',
    vocabulary.join(' · '),
    '',
    'A rule carries every surface it applies to, not one — a focus rule is listed under',
    `buttons, forms, dialogs and links alike. ${unclassified} rules match no surface and are`,
    'reachable by category heading or by symbol below.',
    '',
    '## 2. Or search by a symbol already in your code',
    '',
    'Event handlers, ARIA attributes, CSS properties, element names — `onSubmit`,',
    '`aria-live`, `:focus-visible`, `overscroll-behavior`. Scan the file you are working',
    'on, then search for what you find.',
    '',
    '## 3. Then fetch',
    '',
    `- one rule, with its good and bad example source: \`${SITE}/principles/<id>.md\``,
    `- one category, rules and prose only: \`${SITE}/categories/<category>.md\``,
    `- a broad sweep when nothing above narrows it: \`${SITE}/principles/must.md\``,
    '',
  ];

  for (const c of categories) {
    const items = published.filter((p) => p.category === c.id);
    if (!items.length) continue;
    out.push(`## ${c.id} (${items.length})`, '');
    for (const p of items) {
      const priority = agentRules[p.id]?.priority ?? '—';
      // Surfaces and symbols are both just search targets, so they share one list
      // rather than inventing two annotation syntaxes to explain.
      const match = [...surfaces.get(p.id)!, ...triggers.get(p.id)!];
      const suffix = match.length ? ` · ${match.join(' ')}` : '';
      out.push(`- \`${p.id}\` ${priority} — ${p.title}${suffix}`);
    }
    out.push('');
  }

  return out.join('\n');
}

function mustMd(): string {
  const must = published.filter((p) => agentRules[p.id]?.priority === 'MUST');
  const out = [
    '# MUST rules',
    '',
    `${must.length} of ${published.length} rules are MUST. This file is the whole set,`,
    'phrased to be checked against a diff.',
    '',
    `For the good and bad example that disambiguates any one of them, fetch`,
    `\`${SITE}/principles/<id>.md\` — ids are the backticked strings below.`,
    '',
  ];

  for (const c of categories) {
    const items = must.filter((p) => p.category === c.id);
    if (!items.length) continue;
    out.push(`## ${c.id}`, '');
    for (const p of items) {
      out.push(`- \`${p.id}\` — ${agentRules[p.id].rule}`);
    }
    out.push('');
  }

  return out.join('\n');
}

function categoryMd(categoryId: string): string {
  const c = categories.find((x) => x.id === categoryId)!;
  const items = published.filter((p) => p.category === categoryId);
  return [
    `# ${c.title}`,
    '',
    `> ${c.description}. ${items.length} rules.`,
    '',
    'Rules and reasoning only — no example code, to keep this affordable. For the',
    'good and bad component source of any rule, fetch its own payload.',
    '',
    '---',
    '',
    items.map((p) => ruleSection(p)).join('\n\n---\n\n'),
    '',
  ].join('\n');
}

// Wipe and rebuild, so a renamed or deleted principle cannot leave a stale payload
// being served — these directories are generated in full every time.
rmSync(PRINCIPLES_DIR, { recursive: true, force: true });
rmSync(CATEGORIES_DIR, { recursive: true, force: true });
mkdirSync(PRINCIPLES_DIR, { recursive: true });
mkdirSync(CATEGORIES_DIR, { recursive: true });

let missingExamples = 0;
for (const p of published) {
  const md = rulePayload(p);
  writeFileSync(join(PRINCIPLES_DIR, `${p.id}.md`), md, 'utf8');
  writeFileSync(
    join(PRINCIPLES_DIR, `${p.id}.json`),
    JSON.stringify(ruleJson(p), null, 2),
    'utf8',
  );
  if (!examples.has(p.badExampleKey) || !examples.has(p.goodExampleKey)) missingExamples++;
}

const index = indexMd();
const must = mustMd();
writeFileSync(join(PRINCIPLES_DIR, 'index.md'), index, 'utf8');
writeFileSync(join(PRINCIPLES_DIR, 'must.md'), must, 'utf8');

for (const c of categories) {
  if (!published.some((p) => p.category === c.id)) continue;
  writeFileSync(join(CATEGORIES_DIR, `${c.id}.md`), categoryMd(c.id), 'utf8');
}

console.log(`  principles/          ${published.length * 2} files (.md + .json per rule)`);
const surfaced = published.filter((p) => surfaces.get(p.id)!.length).length;
const triggered = published.filter((p) => triggers.get(p.id)!.length).length;
console.log(
  `  principles/index.md  ${String(tokens(index)).padStart(6)} tokens` +
    ` (${surfaced}/${published.length} surfaced, ${triggered}/${published.length} with symbols)`,
);
console.log(`  principles/must.md   ${String(tokens(must)).padStart(6)} tokens`);
for (const c of categories) {
  if (!published.some((p) => p.category === c.id)) continue;
  console.log(`  categories/${c.id.padEnd(13)}${String(tokens(categoryMd(c.id))).padStart(6)} tokens`);
}

/**
 * The example source is the reason these payloads exist, so its absence is a build
 * failure rather than a quietly thinner file. Same posture as the llms.txt guard.
 */
if (missingExamples > 0) {
  throw new Error(
    `${missingExamples} principle(s) have a bad/goodExampleKey with no matching component — ` +
      'the per-rule payloads would ship without the code they exist to carry.',
  );
}
console.log(`\nAll ${published.length} rules carry both example sources.`);
